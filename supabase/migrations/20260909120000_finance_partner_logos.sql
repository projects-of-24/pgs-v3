-- Finance partner logos (W1): CMS-editable image swap for #purpleFinance marquee.
-- No click URL in this gate — image_asset_id only (+ name, order, published).
-- Suggested upload size documented in admin registry / FINANCE-MODULAR.md:
--   280×80 px PNG/WebP (or 140×40 @2x), transparent bg, under ~100 KB.

create table public.finance_partner_logos (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 80),
  image_asset_id uuid references public.media_assets(id) on delete set null,
  published boolean not null default false,
  display_order integer not null default 0 check (display_order >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.finance_partner_logos is
  'Finance page partner logo marquee. Swap image via media_assets; no href in W1.';
comment on column public.finance_partner_logos.image_asset_id is
  'Recommended asset: 280x80 px PNG/WebP (@2x for 140x40 display), transparent, <100KB.';

create index finance_partner_logos_published_order_idx
  on public.finance_partner_logos (published, display_order, id);

alter table public.finance_partner_logos enable row level security;

create policy "public reads finance partner logos"
  on public.finance_partner_logos
  for select to anon, authenticated
  using (published);

create policy "staff read finance partner logos"
  on public.finance_partner_logos
  for select to authenticated
  using (private.has_staff_permission('content.read'));

create policy "staff manage finance partner logos"
  on public.finance_partner_logos
  for all to authenticated
  using (private.has_staff_permission('content.manage'))
  with check (private.has_staff_permission('content.manage'));

grant select on public.finance_partner_logos to anon, authenticated;
grant insert, update, delete on public.finance_partner_logos to authenticated;

create trigger audit_finance_partner_logos_admin
  after insert or update or delete on public.finance_partner_logos
  for each row execute function private.audit_admin_change();

